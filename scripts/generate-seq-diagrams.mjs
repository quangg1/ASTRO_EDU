/**
 * Generate sequence diagram .drawio files at SYSTEM ARCHITECTURE level (not code names).
 * Run: npm run diagrams:seq
 *
 * Output: docs/diagrams/sequence/UC-XX-*.drawio
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { buildSeqDrawio } from './lib/seq-diagram-builder.mjs';
import { DIAGRAMS } from './seq-diagram-definitions.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'docs/diagrams/sequence');

function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const index = [];
  for (const def of DIAGRAMS) {
    const outPath = path.join(OUT_DIR, `${def.file}.drawio`);
    fs.writeFileSync(outPath, buildSeqDrawio(def), 'utf8');
    index.push({ file: `${def.file}.drawio`, title: def.title });
    console.log('wrote', path.relative(ROOT, outPath));
  }
  const readme = `# Sequence diagrams (draw.io)

Generated by \`npm run diagrams:seq\` — **use-case flows over deployment architecture**, not reverse-engineered from code identifiers.

Open in [diagrams.net](https://app.diagrams.net) or VS Code Draw.io Integration.

| File | Use case |
|------|----------|
${index.map((r) => `| [${r.file}](${r.file}) | ${r.title} |`).join('\n')}

## Principles (design first — code later)

1. **Lifeline** = system component: Web UI, API Server, Database, AI Service, …
2. **Message** = business action, e.g. *Request post list* — no route names, hooks, or model fields.
3. **alt / opt** = use-case branches (guest vs student, approve vs reject), not implementation branches.

## UML notation

- **Actor**: human role (Student, Teacher, Administrator, Moderator)
- **Solid arrow**: request / command
- **Dashed arrow**: response / returned data
- **Self-call**: internal processing on one lifeline (UI or API)

## Reference architecture

\`\`\`
User → Web UI (Next.js) → API Server (Node.js) → MongoDB
                        ↘ AI Service (Python) — when LLM/RAG is needed
\`\`\`

See also: \`docs/ARCHITECTURE_MERGED.md\`, \`client/DOMAIN_MAP.md\`.

## Regenerate

\`\`\`bash
npm run diagrams:seq
\`\`\`

Edit flows in \`scripts/seq-diagram-definitions.mjs\`.
`;
  fs.writeFileSync(path.join(OUT_DIR, 'README.md'), readme, 'utf8');
  console.log(`\n${index.length} diagrams → ${path.relative(ROOT, OUT_DIR)}`);
}

main();
