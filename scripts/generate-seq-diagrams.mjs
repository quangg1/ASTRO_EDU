/**
 * Generate UML sequence diagram .drawio files (Register-template granularity).
 * Run: npm run diagrams:seq
 *
 * Output: docs/diagrams/sequence/UC-XX-*.drawio
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { buildSeqDrawio } from './lib/seq-diagram-builder.mjs';
import { DIAGRAMS } from './seq-diagram-definitions.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = path.join(ROOT, 'docs/diagrams/sequence');

function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  const index = [];
  for (const def of DIAGRAMS) {
    const outPath = path.join(OUT_DIR, `${def.file}.drawio`);
    fs.writeFileSync(outPath, buildSeqDrawio(def), 'utf8');
    index.push({ file: `${def.file}.drawio`, title: def.title });
    console.log('wrote', path.relative(ROOT, outPath));
  }
  const readme = `# Sequence diagrams (draw.io)

Generated by \`npm run diagrams:seq\` — **Page → client API → route → service → MongoDB**, with **alt/opt** fragments (same style as Register UC).

Open in [diagrams.net](https://app.diagrams.net) or VS Code Draw.io Integration.

| File | Use case |
|------|----------|
${index.map((r) => `| [${r.file}](${r.file}) | ${r.title} |`).join('\n')}

## Notation

- **Actor**: stick figure (human role)
- **Lifelines**: boundary (page/widget) → control (API route/service) → entity (MongoDB / external)
- **Solid arrow**: request / call
- **Dashed arrow**: response / return
- **alt / opt frames**: conditional paths (validation, errors, branches)
- **Self-call**: internal UI/state logic on one lifeline

## Regenerate

\`\`\`bash
npm run diagrams:seq
\`\`\`

Edit flows in \`scripts/seq-diagram-definitions.mjs\`.
`;
  fs.writeFileSync(path.join(OUT_DIR, 'README.md'), readme, 'utf8');
  console.log(`\n${index.length} diagrams → ${path.relative(ROOT, OUT_DIR)}`);
}

main();
